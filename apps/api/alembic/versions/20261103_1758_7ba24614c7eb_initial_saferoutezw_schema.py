# A public alert may only be inserted - or moved to 'published' - when its approving
# review exists, is an 'approved' decision, belongs to the same incident and bulletin
# version, was made by an active human editor, and has not been superseded by a later
# non-approving decision. Withdrawing an existing alert is always allowed.
FN_REQUIRE_HUMAN_APPROVAL = """
CREATE FUNCTION saferoutezw_require_human_approval() RETURNS trigger
LANGUAGE plpgsql AS $fn$
DECLARE
    approval editorial_reviews%ROWTYPE;
    reviewer users%ROWTYPE;
BEGIN
    IF TG_OP = 'UPDATE'
       AND NEW.incident_id = OLD.incident_id
       AND NEW.bulletin_version_id = OLD.bulletin_version_id
       AND NEW.approval_review_id = OLD.approval_review_id
       AND NOT (NEW.status = 'published' AND OLD.status <> 'published') THEN
        RETURN NEW;
    END IF;

    SELECT * INTO approval FROM editorial_reviews WHERE id = NEW.approval_review_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'public alert requires an existing approving editorial review'
            USING ERRCODE = 'check_violation';
    END IF;
    IF approval.decision <> 'approved' THEN
        RAISE EXCEPTION 'review % is "%": only an approved review can back a public alert',
            approval.id, approval.decision
            USING ERRCODE = 'check_violation';
    END IF;
    IF approval.incident_id <> NEW.incident_id THEN
        RAISE EXCEPTION 'approving review % belongs to a different incident', approval.id
            USING ERRCODE = 'check_violation';
    END IF;
    IF approval.bulletin_version_id IS DISTINCT FROM NEW.bulletin_version_id THEN
        RAISE EXCEPTION 'approving review % covers a different bulletin version', approval.id
            USING ERRCODE = 'check_violation';
    END IF;

    SELECT * INTO reviewer FROM users WHERE id = approval.reviewer_id;
    IF NOT FOUND OR NOT reviewer.is_active OR reviewer.role NOT IN ('admin', 'editor') THEN
        RAISE EXCEPTION 'approving review % was not made by an active human editor', approval.id
            USING ERRCODE = 'check_violation';
    END IF;

    IF EXISTS (
        SELECT 1 FROM editorial_reviews later
        WHERE later.incident_id = approval.incident_id
          AND later.bulletin_version_id = approval.bulletin_version_id
          AND later.decision <> 'approved'
          AND later.reviewed_at > approval.reviewed_at
    ) THEN
        RAISE EXCEPTION 'approving review % was superseded by a later decision', approval.id
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$fn$
"""

