"""Write the transport-intelligence taxonomy as a TypeScript module for the web app.

The web app never hand-copies category names: ``apps/web/src/lib/taxonomy.generated.ts`` is produced
here from ``app.taxonomy`` and a backend test fails if the committed file drifts.

    python scripts/export_taxonomy.py [output.ts]
"""

from __future__ import annotations

import sys
from pathlib import Path

API_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(API_ROOT))

from app.taxonomy import (  # noqa: E402
    CATEGORY_LABELS,
    RECORD_KIND_LABELS,
    SUBTYPES,
    TAXONOMY_VERSION,
    GeographicScope,
    PrimaryCategory,
    PublicationOutput,
    RecordKind,
    RecordStatus,
    TemporalStatus,
    subtype_label,
)

DEFAULT_OUTPUT = API_ROOT.parents[1] / "apps" / "web" / "src" / "lib" / "taxonomy.generated.ts"


def _array(name: str, values) -> str:
    items = ",\n".join(f'  "{v}"' for v in values)
    return f"export const {name} = [\n{items},\n] as const;\n"


def render() -> str:
    parts = [
        "// GENERATED by apps/api/scripts/export_taxonomy.py from app/taxonomy.py. Do not edit by hand.\n",
        f'export const TAXONOMY_VERSION = "{TAXONOMY_VERSION}";\n',
        _array("PRIMARY_CATEGORIES", [c.value for c in PrimaryCategory]),
        "export type PrimaryCategory = (typeof PRIMARY_CATEGORIES)[number];\n",
        _array("RECORD_KINDS", [k.value for k in RecordKind]),
        "export type RecordKind = (typeof RECORD_KINDS)[number];\n",
        _array("TEMPORAL_STATUSES", [t.value for t in TemporalStatus]),
        "export type TemporalStatus = (typeof TEMPORAL_STATUSES)[number];\n",
        _array("GEOGRAPHIC_SCOPES", [g.value for g in GeographicScope]),
        "export type GeographicScope = (typeof GEOGRAPHIC_SCOPES)[number];\n",
        _array("RECORD_STATUSES", [s.value for s in RecordStatus]),
        "export type RecordStatus = (typeof RECORD_STATUSES)[number];\n",
        _array("PUBLICATION_OUTPUTS", [o.value for o in PublicationOutput]),
        "export type PublicationOutputType = (typeof PUBLICATION_OUTPUTS)[number];\n",
        "export const CATEGORY_LABELS: Record<PrimaryCategory, string> = {\n"
        + "".join(f'  {c}: "{CATEGORY_LABELS[c]}",\n' for c in CATEGORY_LABELS)
        + "};\n",
        "export const RECORD_KIND_LABELS: Record<RecordKind, string> = {\n"
        + "".join(f'  {k}: "{v}",\n' for k, v in RECORD_KIND_LABELS.items())
        + "};\n",
        "export const SUBTYPES: Record<PrimaryCategory, readonly string[]> = {\n"
        + "".join(
            f"  {c.value}: [" + ", ".join(f'"{s}"' for s in subs) + "],\n" for c, subs in SUBTYPES.items()
        )
        + "};\n",
        "export const SUBTYPE_LABELS: Record<string, string> = {\n"
        + "".join(
            f'  {s}: "{subtype_label(s)}",\n' for s in dict.fromkeys(x for subs in SUBTYPES.values() for x in subs)
        )
        + "};\n",
    ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    output = Path(args[0]) if args else DEFAULT_OUTPUT
    output.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
